
CREATE TABLE Categoria (
  id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  descripcion VARCHAR(255),
  tipo VARCHAR(50) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'activa'
);

CREATE TABLE Proveedor (
  id_proveedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rut VARCHAR(12) NOT NULL UNIQUE,
  razon_social VARCHAR(150) NOT NULL,
  direccion VARCHAR(200),
  fecha_incorporacion DATE NOT NULL,
  estado_proveedor VARCHAR(30) NOT NULL DEFAULT 'activo'
);

CREATE TABLE Contacto (
  id_contacto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proveedor INT NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  apellido VARCHAR(80) NOT NULL,
  cargo VARCHAR(80),
  correo_electronico VARCHAR(120),
  telefono VARCHAR(20),
  estado VARCHAR(30) NOT NULL DEFAULT 'activo',
  FOREIGN KEY (id_proveedor) REFERENCES Proveedor(id_proveedor)
);

CREATE TABLE Insumo (
  id_insumo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria INT NOT NULL,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  descripcion VARCHAR(255),
  unidad_medida VARCHAR(20) NOT NULL,
  stock_actual NUMERIC(12,2) NOT NULL DEFAULT 0,
  stock_maximo NUMERIC(12,2) NOT NULL,
  tipo_almacenamiento VARCHAR(20) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'activo',
  FOREIGN KEY (id_categoria) REFERENCES Categoria(id_categoria),
  CHECK (tipo_almacenamiento IN ('normal', 'refrigerado', 'congelado')),
  CHECK (stock_actual >= 0),
  CHECK (stock_maximo >= 0)
);

CREATE TABLE Proveedor_Insumo (
  id_proveedor_insumo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proveedor INT NOT NULL,
  id_insumo INT NOT NULL,
  precio_acordado NUMERIC(12,2) NOT NULL,
  plazo_entrega_dias INT NOT NULL,
  fecha_inicio_suministro DATE NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'activo',
  FOREIGN KEY (id_proveedor) REFERENCES Proveedor(id_proveedor),
  FOREIGN KEY (id_insumo) REFERENCES Insumo(id_insumo),
  UNIQUE (id_proveedor, id_insumo),
  CHECK (precio_acordado >= 0),
  CHECK (plazo_entrega_dias >= 0)
);

CREATE TABLE Orden_Compra (
  id_orden_compra INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proveedor INT NOT NULL,
  numero_orden VARCHAR(30) NOT NULL UNIQUE,
  fecha_emision DATE NOT NULL,
  fecha_entrega_estimada DATE,
  estado VARCHAR(30) NOT NULL DEFAULT 'emitida',
  observaciones VARCHAR(255),
  FOREIGN KEY (id_proveedor) REFERENCES Proveedor(id_proveedor),
  CHECK (fecha_entrega_estimada IS NULL OR fecha_entrega_estimada >= fecha_emision)
);

CREATE TABLE Detalle_Orden_Compra (
  id_detalle_orden_compra INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orden_compra INT NOT NULL,
  id_insumo INT NOT NULL,
  cantidad_solicitada NUMERIC(12,2) NOT NULL,
  precio_unitario NUMERIC(12,2) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'pendiente',
  observaciones VARCHAR(255),
  FOREIGN KEY (id_orden_compra) REFERENCES Orden_Compra(id_orden_compra),
  FOREIGN KEY (id_insumo) REFERENCES Insumo(id_insumo),
  UNIQUE (id_orden_compra, id_insumo),
  CHECK (cantidad_solicitada > 0),
  CHECK (precio_unitario >= 0)
);

CREATE TABLE Factura (
  id_factura INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orden_compra INT NOT NULL,
  numero_factura VARCHAR(30) NOT NULL UNIQUE,
  fecha_emision DATE NOT NULL,
  monto_total NUMERIC(14,2) NOT NULL,
  estado_pago VARCHAR(30) NOT NULL DEFAULT 'pendiente',
  FOREIGN KEY (id_orden_compra) REFERENCES Orden_Compra(id_orden_compra),
  CHECK (monto_total >= 0)
);

CREATE TABLE Detalle_Factura (
  id_detalle_factura INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_factura INT NOT NULL,
  id_insumo INT NOT NULL,
  cantidad_facturada NUMERIC(12,2) NOT NULL,
  precio_unitario NUMERIC(12,2) NOT NULL,
  porcentaje_descuento NUMERIC(5,2) NOT NULL DEFAULT 0,
  observaciones VARCHAR(255),
  FOREIGN KEY (id_factura) REFERENCES Factura(id_factura),
  FOREIGN KEY (id_insumo) REFERENCES Insumo(id_insumo),
  UNIQUE (id_factura, id_insumo),
  CHECK (cantidad_facturada > 0),
  CHECK (precio_unitario >= 0),
  CHECK (porcentaje_descuento BETWEEN 0 AND 100)
);

CREATE TABLE Guia_Despacho (
  id_guia_despacho INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_factura INT NOT NULL,
  numero_guia VARCHAR(30) NOT NULL UNIQUE,
  fecha_emision DATE NOT NULL,
  transportista VARCHAR(100),
  estado VARCHAR(30) NOT NULL DEFAULT 'emitida',
  FOREIGN KEY (id_factura) REFERENCES Factura(id_factura)
);

CREATE TABLE Certificado_Calidad (
  id_certificado_calidad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_certificado VARCHAR(30) NOT NULL UNIQUE,
  fecha_emision DATE NOT NULL,
  resultado VARCHAR(30) NOT NULL,
  observaciones VARCHAR(255)
);

CREATE TABLE Recepcion (
  id_recepcion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proveedor INT NOT NULL,
  id_guia_despacho INT NULL,
  numero_recepcion VARCHAR(30) NOT NULL UNIQUE,
  fecha_ingreso DATE NOT NULL,
  estado_aprobacion_calidad VARCHAR(30) NOT NULL DEFAULT 'pendiente',
  observaciones_recepcion VARCHAR(255),
  FOREIGN KEY (id_proveedor) REFERENCES Proveedor(id_proveedor),
  FOREIGN KEY (id_guia_despacho) REFERENCES Guia_Despacho(id_guia_despacho)
);

CREATE TABLE Bodega (
  id_bodega INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  tipo_bodega VARCHAR(30) NOT NULL,
  capacidad NUMERIC(12,2) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'activa',
  CHECK (tipo_bodega IN ('normal', 'refrigerada', 'congelada', 'productos terminados')),
  CHECK (capacidad > 0)
);

CREATE TABLE Ubicacion (
  id_ubicacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_bodega INT NOT NULL,
  pasillo VARCHAR(10) NOT NULL,
  rack VARCHAR(10) NOT NULL,
  nivel VARCHAR(10) NOT NULL,
  codigo_ubicacion VARCHAR(30) NOT NULL UNIQUE,
  FOREIGN KEY (id_bodega) REFERENCES Bodega(id_bodega)
);

CREATE TABLE Pallet_Insumo (
  id_pallet_insumo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ubicacion INT NOT NULL,
  codigo_pallet VARCHAR(30) NOT NULL UNIQUE,
  capacidad_maxima NUMERIC(12,2) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'disponible',
  material_pallet VARCHAR(30) NOT NULL,
  FOREIGN KEY (id_ubicacion) REFERENCES Ubicacion(id_ubicacion),
  CHECK (capacidad_maxima > 0)
);

CREATE TABLE Pallet_Terminado (
  id_pallet_terminado INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ubicacion INT NOT NULL,
  codigo_pallet VARCHAR(30) NOT NULL UNIQUE,
  capacidad_maxima NUMERIC(12,2) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'disponible',
  material_pallet VARCHAR(30) NOT NULL,
  FOREIGN KEY (id_ubicacion) REFERENCES Ubicacion(id_ubicacion),
  CHECK (capacidad_maxima > 0)
);

CREATE TABLE Lote_Insumo (
  id_lote_insumo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_recepcion INT NOT NULL,
  id_insumo INT NOT NULL,
  id_certificado_calidad INT NULL,
  id_pallet_insumo INT NOT NULL,
  numero_lote VARCHAR(30) NOT NULL,
  fecha_elaboracion DATE NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  cantidad_recibida NUMERIC(12,2) NOT NULL,
  cantidad_disponible NUMERIC(12,2) NOT NULL,
  FOREIGN KEY (id_recepcion) REFERENCES Recepcion(id_recepcion),
  FOREIGN KEY (id_insumo) REFERENCES Insumo(id_insumo),
  FOREIGN KEY (id_certificado_calidad) REFERENCES Certificado_Calidad(id_certificado_calidad),
  FOREIGN KEY (id_pallet_insumo) REFERENCES Pallet_Insumo(id_pallet_insumo),
  CHECK (fecha_vencimiento >= fecha_elaboracion),
  CHECK (cantidad_recibida > 0),
  CHECK (cantidad_disponible >= 0 AND cantidad_disponible <= cantidad_recibida)
);

CREATE TABLE Producto (
  id_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria INT NOT NULL,
  codigo VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(100) NOT NULL,
  descripcion VARCHAR(255),
  stock_actual NUMERIC(12,2) NOT NULL DEFAULT 0,
  stock_maximo NUMERIC(12,2) NOT NULL,
  tipo_almacenamiento VARCHAR(20) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'activo',
  FOREIGN KEY (id_categoria) REFERENCES Categoria(id_categoria),
  CHECK (tipo_almacenamiento IN ('normal', 'refrigerado', 'congelado')),
  CHECK (stock_actual >= 0),
  CHECK (stock_maximo >= 0)
);

CREATE TABLE Receta (
  id_receta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto INT NOT NULL,
  fecha_creacion DATE NOT NULL,
  version VARCHAR(20) NOT NULL,
  estado_vigencia VARCHAR(20) NOT NULL DEFAULT 'vigente',
  procedimiento_general TEXT,
  FOREIGN KEY (id_producto) REFERENCES Producto(id_producto),
  UNIQUE (id_producto, version),
  CHECK (estado_vigencia IN ('vigente', 'inactiva'))
);

CREATE UNIQUE INDEX uq_receta_vigente ON Receta(id_producto) WHERE estado_vigencia = 'vigente';

CREATE TABLE Detalle_Receta (
  id_detalle_receta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_receta INT NOT NULL,
  id_insumo INT NOT NULL,
  cantidad_requerida NUMERIC(12,3) NOT NULL,
  unidad_medida VARCHAR(20) NOT NULL,
  orden_uso INT NOT NULL,
  observaciones VARCHAR(255),
  FOREIGN KEY (id_receta) REFERENCES Receta(id_receta),
  FOREIGN KEY (id_insumo) REFERENCES Insumo(id_insumo),
  UNIQUE (id_receta, id_insumo),
  CHECK (cantidad_requerida > 0),
  CHECK (orden_uso > 0)
);

CREATE TABLE Area (
  id_area INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  descripcion VARCHAR(255),
  estado VARCHAR(30) NOT NULL DEFAULT 'activa',
  presupuesto_mensual NUMERIC(14,2) NOT NULL DEFAULT 0,
  CHECK (presupuesto_mensual >= 0)
);

CREATE TABLE Trabajador (
  id_trabajador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_area INT NOT NULL,
  rut VARCHAR(12) NOT NULL UNIQUE,
  nombre VARCHAR(80) NOT NULL,
  apellido VARCHAR(80) NOT NULL,
  fecha_ingreso DATE NOT NULL,
  certificado_salud VARCHAR(100),
  cargo VARCHAR(80) NOT NULL,
  estado_laboral VARCHAR(30) NOT NULL DEFAULT 'activo',
  FOREIGN KEY (id_area) REFERENCES Area(id_area)
);

CREATE TABLE Jefe_Area (
  id_jefe_area INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_trabajador INT NOT NULL UNIQUE,
  especializacion VARCHAR(100),
  titulo_certificacion VARCHAR(100),
  fecha_nombramiento DATE NOT NULL,
  bono_responsabilidad NUMERIC(12,2) NOT NULL DEFAULT 0,
  FOREIGN KEY (id_trabajador) REFERENCES Trabajador(id_trabajador),
  CHECK (bono_responsabilidad >= 0)
);

CREATE TABLE Operario (
  id_operario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_trabajador INT NOT NULL UNIQUE,
  turno VARCHAR(20) NOT NULL,
  especialidad VARCHAR(100),
  nivel_experiencia VARCHAR(30),
  fecha_ultima_capacitacion DATE,
  FOREIGN KEY (id_trabajador) REFERENCES Trabajador(id_trabajador)
);

CREATE TABLE Orden_Produccion (
  id_orden INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto INT NOT NULL,
  id_area INT NOT NULL,
  id_solicitante INT NOT NULL,
  id_jefe_area INT NOT NULL,
  fecha_solicitud DATE NOT NULL,
  fecha_inicio DATE,
  fecha_termino DATE,
  cantidad_solicitada NUMERIC(12,2) NOT NULL,
  estado VARCHAR(30) NOT NULL DEFAULT 'solicitada',
  observaciones VARCHAR(255),
  FOREIGN KEY (id_producto) REFERENCES Producto(id_producto),
  FOREIGN KEY (id_area) REFERENCES Area(id_area),
  FOREIGN KEY (id_solicitante) REFERENCES Trabajador(id_trabajador),
  FOREIGN KEY (id_jefe_area) REFERENCES Jefe_Area(id_jefe_area),
  CHECK (cantidad_solicitada > 0),
  CHECK (fecha_inicio IS NULL OR fecha_inicio >= fecha_solicitud),
  CHECK (fecha_termino IS NULL OR fecha_inicio IS NULL OR fecha_termino >= fecha_inicio)
);

CREATE TABLE Participacion_Operario (
  id_participacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orden INT NOT NULL,
  id_operario INT NOT NULL,
  rol VARCHAR(50) NOT NULL,
  fecha_asignacion DATE NOT NULL,
  horas_trabajadas NUMERIC(6,2) NOT NULL DEFAULT 0,
  estado VARCHAR(30) NOT NULL DEFAULT 'asignado',
  FOREIGN KEY (id_orden) REFERENCES Orden_Produccion(id_orden),
  FOREIGN KEY (id_operario) REFERENCES Operario(id_operario),
  UNIQUE (id_orden, id_operario),
  CHECK (horas_trabajadas >= 0)
);

CREATE TABLE Lote_Producto_Terminado (
  id_lote_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto INT NOT NULL,
  id_orden INT NOT NULL,
  id_pallet_terminado INT NOT NULL,
  numero_lote VARCHAR(30) NOT NULL,
  fecha_elaboracion DATE NOT NULL,
  fecha_vencimiento DATE NOT NULL,
  cantidad_producida NUMERIC(12,2) NOT NULL,
  cantidad_disponible NUMERIC(12,2) NOT NULL,
  FOREIGN KEY (id_producto) REFERENCES Producto(id_producto),
  FOREIGN KEY (id_orden) REFERENCES Orden_Produccion(id_orden),
  FOREIGN KEY (id_pallet_terminado) REFERENCES Pallet_Terminado(id_pallet_terminado),
  CHECK (fecha_vencimiento >= fecha_elaboracion),
  CHECK (cantidad_producida > 0),
  CHECK (cantidad_disponible >= 0 AND cantidad_disponible <= cantidad_producida)
);

